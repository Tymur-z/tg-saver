from __future__ import annotations

import logging
from typing import Any, Dict, List, Optional

from aiogram import Bot
from aiogram.types import Message

from database.connection import Database
from database.repositories.chat_repo import ChatRepository
from database.repositories.forward_repo import ForwardRepository
from database.repositories.profile_repo import ProfileRepository
from database.repositories.route_repo import RouteRepository
from forwarder.media_handler import MediaHandler
from forwarder.queue import ForwardJob, ForwardQueue

logger = logging.getLogger(__name__)


class ForwardEngine:

    def __init__(self, bot: Bot, db: Database, queue: ForwardQueue) -> None:
        self.bot = bot
        self.db = db
        self.queue = queue

    async def process_incoming_message(
        self,
        message: Message,
        album_messages: Optional[List[Message]] = None,
    ) -> None:
        if message.from_user and message.from_user.id == self.bot.id:
            logger.debug("Skipping message %s generated by the bot itself.", message.message_id)
            return

        source_chat_id = message.chat.id
        title = message.chat.title or message.chat.full_name or f"Chat {source_chat_id}"
        chat_type = message.chat.type

        async with self.db.connect() as conn:
            profile_repo = ProfileRepository(conn)
            if await profile_repo.is_system_paused():
                logger.debug("Forwarding is currently paused globally. Skipping message %s", message.message_id)
                return

            chat_repo = ChatRepository(conn)
            await chat_repo.upsert_chat(
                chat_id=source_chat_id,
                title=title,
                chat_type=chat_type,
                username=message.chat.username,
            )

            route_repo = RouteRepository(conn)
            active_routes = await route_repo.get_routes_for_source(source_chat_id, active_only=True)

        if not active_routes:
            return

        media_type = MediaHandler.detect_type(message)
        text_content = MediaHandler.get_text_or_caption(message).lower()

        for route in active_routes:
            route_id = route["id"]
            dest_chat_id = route["destination_chat_id"]

            if dest_chat_id == source_chat_id:
                logger.warning("Detected self-loop on route %s: source equals destination. Skipping.", route_id)
                continue

            allowed_types: List[str] = route.get("filter_media_types", [])
            if allowed_types and media_type not in allowed_types:
                async with self.db.connect() as conn:
                    repo = ForwardRepository(conn)
                    await repo.mark_filtered(
                        route_id,
                        source_chat_id,
                        message.message_id,
                        dest_chat_id,
                        f"Media type '{media_type}' not in allowed list {allowed_types}",
                    )
                continue

            include_keywords: List[str] = route.get("filter_keywords", [])
            if include_keywords and not any(kw.lower() in text_content for kw in include_keywords):
                async with self.db.connect() as conn:
                    repo = ForwardRepository(conn)
                    await repo.mark_filtered(
                        route_id,
                        source_chat_id,
                        message.message_id,
                        dest_chat_id,
                        "Message does not contain required include keywords",
                    )
                continue

            exclude_keywords: List[str] = route.get("filter_exclude_keywords", [])
            if exclude_keywords and any(kw.lower() in text_content for kw in exclude_keywords):
                async with self.db.connect() as conn:
                    repo = ForwardRepository(conn)
                    await repo.mark_filtered(
                        route_id,
                        source_chat_id,
                        message.message_id,
                        dest_chat_id,
                        "Message contains excluded keyword",
                    )
                continue

            async with self.db.connect() as conn:
                repo = ForwardRepository(conn)
                if await repo.is_already_forwarded(route_id, source_chat_id, message.message_id):
                    logger.debug("Message %s already forwarded on route %s. Skipping.", message.message_id, route_id)
                    continue

                await repo.record_pending(
                    route_id=route_id,
                    source_chat_id=source_chat_id,
                    source_message_id=message.message_id,
                    dest_chat_id=dest_chat_id,
                    media_group_id=message.media_group_id,
                )

            custom_caption = None
            if route.get("mode") == "copy":
                clean_links = bool(route.get("clean_links", 0))
                clean_tags = bool(route.get("clean_tags", 0))
                clean_mentions = bool(route.get("clean_mentions", 0))
                append_source = bool(route.get("append_source_link", 0))
                if clean_links or clean_tags or clean_mentions or append_source:
                    raw_text = MediaHandler.get_text_or_caption(message)
                    custom_caption = MediaHandler.clean_and_format_text(
                        text=raw_text,
                        clean_links=clean_links,
                        clean_tags=clean_tags,
                        clean_mentions=clean_mentions,
                        append_source_link=append_source,
                        source_title=title,
                        source_username=message.chat.username,
                    )

            job = ForwardJob(
                route_id=route_id,
                source_chat_id=source_chat_id,
                source_message_id=message.message_id,
                dest_chat_id=dest_chat_id,
                mode=route.get("mode", "forward"),
                media_type=media_type,
                message=message,
                media_group_id=message.media_group_id,
                album_messages=album_messages,
                custom_caption=custom_caption,
                shadow_dest_chat_id=route.get("shadow_dest_chat_id"),
            )
            await self.queue.enqueue(job)
